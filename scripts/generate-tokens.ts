/**
 * Generates src/styles/tokens.css from design/tokens.json (the L8Play design system).
 *
 * Every token becomes a CSS custom property prefixed with `--l8-` so it never collides with
 * Tailwind's own theme namespaces (--color-*, --radius-*, --shadow-*, --font-*). Tailwind maps
 * them in src/styles/globals.css. Run with `bun run tokens` after changing design/tokens.json.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

interface TokenEntry {
  name: string;
  value: string | Record<string, string>;
}
interface TypeStyle {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
}
interface DesignTokens {
  color: { themes: { id: string }[]; tokens: TokenEntry[] };
  type: { families: Record<string, string>; groups: { family: string; styles: TypeStyle[] }[] };
  spacing: { tokens: TokenEntry[] };
  radius: { tokens: TokenEntry[] };
  shadow: { tokens: TokenEntry[] };
  size: { tokens: TokenEntry[] };
}

/** Self-hosted variable fonts (Fontsource) register these family names. */
const LOCAL_FONT_NAMES: Record<string, string> = {
  '"Outfit"': '"Outfit Variable", "Outfit"',
  '"JetBrains Mono"': '"JetBrains Mono Variable", "JetBrains Mono"',
};

const ROOT = resolve(import.meta.dirname, "..");
const tokens = JSON.parse(readFileSync(resolve(ROOT, "design/tokens.json"), "utf8")) as DesignTokens;
const themeIds = tokens.color.themes.map((theme) => theme.id);
const primaryTheme = themeIds[0];
if (!primaryTheme) throw new Error("design/tokens.json defines no colour theme");

function valueFor(entry: TokenEntry, theme: string): string {
  if (typeof entry.value === "string") return entry.value;
  return entry.value[theme] ?? entry.value[primaryTheme as string] ?? "";
}

function toCssValue(raw: string): string {
  const alias = /^\{(.+)\}$/.exec(raw);
  return alias ? `var(--l8-${alias[1]})` : raw;
}

function themeBlock(theme: string): string {
  const selector = theme === primaryTheme ? `:root, [data-theme="${theme}"]` : `[data-theme="${theme}"]`;
  const lines = [...tokens.color.tokens, ...tokens.shadow.tokens].map(
    (entry) => `  --l8-${entry.name}: ${toCssValue(valueFor(entry, theme))};`,
  );
  const scheme = theme === primaryTheme ? "dark" : "light";
  return `${selector} {\n  color-scheme: ${scheme};\n${lines.join("\n")}\n}`;
}

function staticBlock(): string {
  const scalar = [...tokens.spacing.tokens, ...tokens.radius.tokens, ...tokens.size.tokens].map(
    (entry) => `  --l8-${entry.name}: ${valueFor(entry, primaryTheme as string)};`,
  );
  const families = Object.entries(tokens.type.families).map(([key, stack]) => {
    const local = Object.entries(LOCAL_FONT_NAMES).reduce((acc, [from, to]) => acc.replace(from, to), stack);
    return `  --l8-font-${key}: ${local};`;
  });
  return `:root {\n${[...scalar, ...families].join("\n")}\n}`;
}

function typographyUtilities(): string {
  return tokens.type.groups
    .flatMap((group) =>
      group.styles.map((style) => {
        const spacing = style.letterSpacing ? `\n  letter-spacing: ${style.letterSpacing};` : "";
        return `@utility type-${style.name} {\n  font-family: var(--l8-font-${group.family});\n  font-size: ${style.fontSize};\n  line-height: ${style.lineHeight};\n  font-weight: ${style.fontWeight};${spacing}\n}`;
      }),
    )
    .join("\n\n");
}

const header = "/* Generated by scripts/generate-tokens.ts from design/tokens.json. Do not edit by hand. */";
writeFileSync(
  resolve(ROOT, "src/styles/tokens.css"),
  [header, ...themeIds.map(themeBlock), staticBlock()].join("\n\n") + "\n",
);
writeFileSync(resolve(ROOT, "src/styles/typography.css"), `${header}\n\n${typographyUtilities()}\n`);
console.log(`tokens.css and typography.css written for themes: ${themeIds.join(", ")}`);
